import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,readdir} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
test('deployment contains one active app, redirects old routes and versions nested imports',async()=>{
 execFileSync(process.execPath,['scripts/build-prototype.mjs'],{cwd:root});
 const read=path=>readFile(new URL(`../dist/${path}`,import.meta.url),'utf8');
 const files=await readdir(new URL('../dist/',import.meta.url));
 for(const retired of ['app.mjs','state.mjs','landing.mjs','fixtures.mjs','workspace.css'])assert.equal(files.includes(retired),false);
 assert.match(await read('index.html'),/See the life/);
 assert.match(await read('index.html'),/data-slide="3"/);
 assert.ok(files.includes('welcome-view.mjs'));
 assert.ok(files.includes('landing.css'));
 assert.match(await read('asset-canvas.html'),/app.html#assets/);
 assert.match(await read('plan.html'),/app.html#planning/);
 assert.equal(JSON.parse(await read('manifest.webmanifest')).start_url,'/app.html');
 const version=JSON.parse(await read('version.json')).version;
 assert.ok((await read('index.html')).includes(`welcome-view.mjs?v=${version}`));
 assert.ok((await read('index.html')).includes(`landing.css?v=${version}`));
 assert.ok((await read('app.html')).includes(`asset-canvas.mjs?v=${version}`));
 assert.ok((await read('app.html')).includes(`finance-theme.css?v=${version}`));
 assert.ok(files.includes('finance-theme.css'));
 assert.ok((await read('app.html')).includes('manifest.webmanifest'));
 assert.ok((await read('planning-view.mjs')).includes(`planning.mjs?v=${version}`));
 assert.ok((await read('planning-outcomes-view.mjs')).includes(`planning-simulation-worker.mjs?v=${version}`));
 assert.ok((await read('planning-simulation-worker.mjs')).includes(`planning-simulation.mjs?v=${version}`));
 assert.ok((await read('planning-simulation.mjs')).includes(`planning.mjs?v=${version}`));
 assert.ok((await read('planning.mjs')).includes(`withdrawals.mjs?v=${version}`));
});
